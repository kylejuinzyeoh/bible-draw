import React from 'react';
import {AbsoluteFill, Composition, Html5Audio, registerRoot, Sequence, staticFile, useCurrentFrame} from 'remotion';
import {C, FPS, H, W, fontFamily} from './shared';
import {Scene1} from './scenes/Scene1';
import {Scene2} from './scenes/Scene2';
import {Scene3} from './scenes/Scene3';
import {Scene4} from './scenes/Scene4';
import {Scene5} from './scenes/Scene5';
import {Scene6} from './scenes/Scene6';

const Grid: React.FC = () => {
  const frame = useCurrentFrame();
  const line = 'rgba(255,255,255,0.04)';
  return (
    <>
      <AbsoluteFill
        style={{
          backgroundImage: `linear-gradient(${line} 1px, transparent 1px), linear-gradient(90deg, ${line} 1px, transparent 1px)`,
          backgroundSize: '90px 90px',
          backgroundPosition: `${frame * 0.3}px ${frame * 0.6}px`,
        }}
      />
      <AbsoluteFill style={{background: 'radial-gradient(ellipse at center, transparent 45%, rgba(0,0,0,0.55) 100%)'}} />
    </>
  );
};

const SCENES: [React.FC, number, number][] = [
  [Scene1, 0, 60],
  [Scene2, 60, 105],
  [Scene3, 105, 210],
  [Scene4, 210, 285],
  [Scene5, 285, 360],
  [Scene6, 360, 450],
];

const BuildStory: React.FC = () => (
  <AbsoluteFill style={{background: C.bg, fontFamily}}>
    <Grid />
    {/* Generated by `npm run audio` — 120 BPM, locked to the beat grid. */}
    <Html5Audio src={staticFile('audio/music.wav')} volume={0.6} />
    <Html5Audio src={staticFile('audio/sfx.wav')} volume={1} />
    {SCENES.map(([Scene, from, to]) => (
      <Sequence key={from} from={from} durationInFrames={to - from}>
        <Scene />
      </Sequence>
    ))}
  </AbsoluteFill>
);

const RemotionRoot: React.FC = () => (
  <Composition id="BuildStory" component={BuildStory} durationInFrames={450} fps={FPS} width={W} height={H} />
);

registerRoot(RemotionRoot);
